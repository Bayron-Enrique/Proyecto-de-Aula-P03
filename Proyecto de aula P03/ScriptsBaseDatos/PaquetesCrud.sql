-- Detalle de vehículos vinculados a una factura.
-- La secuencia fue creada en el esquema TALLER como SEQ_DETALLE_VEHICULO.
CREATE OR REPLACE PACKAGE TALLER.PKG_DETALLE_VEHICULO AS
  PROCEDURE GUARDAR(p_id IN OUT NUMBER, p_factura_id NUMBER, p_placa CHAR);
  PROCEDURE MODIFICAR(p_id NUMBER, p_factura_id NUMBER, p_placa CHAR);
  PROCEDURE CONSULTAR_POR_FACTURA(p_factura_id NUMBER, p_resultado OUT SYS_REFCURSOR);
  PROCEDURE BUSCAR_ID(p_id NUMBER, p_resultado OUT SYS_REFCURSOR);
  PROCEDURE ELIMINAR(p_id NUMBER);
END PKG_DETALLE_VEHICULO;
/

CREATE OR REPLACE PACKAGE BODY TALLER.PKG_DETALLE_VEHICULO AS
  PROCEDURE GUARDAR(p_id IN OUT NUMBER, p_factura_id NUMBER, p_placa CHAR) IS
  BEGIN
    SELECT TALLER.SEQ_DETALLE_VEHICULO.NEXTVAL INTO p_id FROM DUAL;
    INSERT INTO TALLER.DETALLE_VEHICULO (DETALLEVEHICULOID, FACTURA_FACTURAID, VEHICULO_PLACA)
    VALUES (p_id, p_factura_id, p_placa);
  END;

  PROCEDURE MODIFICAR(p_id NUMBER, p_factura_id NUMBER, p_placa CHAR) IS
  BEGIN
    UPDATE TALLER.DETALLE_VEHICULO
       SET FACTURA_FACTURAID = p_factura_id, VEHICULO_PLACA = p_placa
     WHERE DETALLEVEHICULOID = p_id;
    IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20001, 'No existe el detalle de vehículo.'); END IF;
  END;

  PROCEDURE CONSULTAR_POR_FACTURA(p_factura_id NUMBER, p_resultado OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_resultado FOR
      SELECT DV.DETALLEVEHICULOID, DV.FACTURA_FACTURAID,
             V.PLACA, V.MODELO, V.MARCA, V.TIPO_VEHICULO, V.COLOR, V.LINEA, V.CLIENTE_CEDULA
        FROM TALLER.DETALLE_VEHICULO DV
        JOIN TALLER.VEHICULO V ON V.PLACA = DV.VEHICULO_PLACA
       WHERE DV.FACTURA_FACTURAID = p_factura_id
       ORDER BY DV.DETALLEVEHICULOID;
  END;

  PROCEDURE BUSCAR_ID(p_id NUMBER, p_resultado OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_resultado FOR
      SELECT DV.DETALLEVEHICULOID, DV.FACTURA_FACTURAID,
             V.PLACA, V.MODELO, V.MARCA, V.TIPO_VEHICULO, V.COLOR, V.LINEA, V.CLIENTE_CEDULA
        FROM TALLER.DETALLE_VEHICULO DV
        JOIN TALLER.VEHICULO V ON V.PLACA = DV.VEHICULO_PLACA
       WHERE DV.DETALLEVEHICULOID = p_id;
  END;

  PROCEDURE ELIMINAR(p_id NUMBER) IS
  BEGIN
    DELETE FROM TALLER.DETALLE_VEHICULO WHERE DETALLEVEHICULOID = p_id;
    IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20001, 'No existe el detalle de vehículo.'); END IF;
  END;
END PKG_DETALLE_VEHICULO;
