CREATE OR REPLACE PACKAGE BODY TALLER.PKG_AGENDA AS
  PROCEDURE PRC_VALIDAR(p_id NUMBER,p_fecha DATE,p_placa CHAR,p_empleado CHAR,p_estado VARCHAR2,p_articulo NUMBER) IS
    v_duracion NUMBER; v_total NUMBER; v_activo CHAR(1);
  BEGIN
    IF p_estado IS NULL OR p_estado NOT IN ('PENDIENTE','EN PROCESO','COMPLETADA','CANCELADA') THEN RAISE_APPLICATION_ERROR(-20004,'Estado de cita inválido.'); END IF;
    IF p_estado='CANCELADA' THEN RETURN; END IF;
    IF p_fecha IS NULL OR p_articulo IS NULL THEN RAISE_APPLICATION_ERROR(-20005,'La cita requiere fecha y servicio.'); END IF;
    SELECT A.DURACION INTO v_duracion FROM TALLER.ARTICULO A JOIN TALLER.TIPO_ARTICULO T ON T.TIPO_ARTICULO_ID=A.TIPO_ARTICULO_ID WHERE A.ARTICULOID=p_articulo AND UPPER(T.NOMBRE)='SERVICIO' AND A.DURACION>=1;
    SELECT ACTIVO INTO v_activo FROM TALLER.EMPLEADO WHERE CEDULA=p_empleado;
    IF v_activo<>'S' THEN RAISE_APPLICATION_ERROR(-20006,'El empleado está inactivo.'); END IF;
    SELECT COUNT(*) INTO v_total FROM TALLER.AGENDA A LEFT JOIN TALLER.ARTICULO S ON S.ARTICULOID=A.ARTICULO_ARTICULOID
     WHERE A.AGENDAID<>NVL(p_id,0) AND UPPER(TRIM(A.ESTADO))<>'CANCELADA' AND (A.EMPLEADO_CEDULA=p_empleado OR A.VEHICULO_PLACA=p_placa)
       AND (A.FECHA IS NULL OR (A.FECHA<p_fecha+v_duracion/1440 AND p_fecha<A.FECHA+GREATEST(NVL(S.DURACION,1),1)/1440));
    IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20007,'El empleado o vehículo ya tiene una cita en ese horario.'); END IF;
  EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20008,'El empleado o el servicio no existe o no tiene duración válida.');
  END;
  PROCEDURE PRC_GUARDAR(p_id IN OUT NUMBER,p_fecha DATE,p_comentario VARCHAR2,p_placa CHAR,p_empleado CHAR,p_estado VARCHAR2,p_articulo NUMBER) IS
  BEGIN LOCK TABLE TALLER.AGENDA IN SHARE ROW EXCLUSIVE MODE; PRC_VALIDAR(NULL,p_fecha,p_placa,p_empleado,p_estado,p_articulo); SELECT TALLER.SEQ_AGENDAID.NEXTVAL INTO p_id FROM DUAL;
    INSERT INTO TALLER.AGENDA(AGENDAID,FECHA,COMENTARIO,VEHICULO_PLACA,EMPLEADO_CEDULA,ESTADO,ARTICULO_ARTICULOID) VALUES(p_id,p_fecha,p_comentario,p_placa,p_empleado,p_estado,p_articulo); END;
  PROCEDURE PRC_MODIFICAR(p_id NUMBER,p_fecha DATE,p_comentario VARCHAR2,p_placa CHAR,p_empleado CHAR,p_estado VARCHAR2,p_articulo NUMBER) IS
  BEGIN LOCK TABLE TALLER.AGENDA IN SHARE ROW EXCLUSIVE MODE; PRC_VALIDAR(p_id,p_fecha,p_placa,p_empleado,p_estado,p_articulo);
    UPDATE TALLER.AGENDA SET FECHA=p_fecha,COMENTARIO=p_comentario,VEHICULO_PLACA=p_placa,EMPLEADO_CEDULA=p_empleado,ESTADO=p_estado,ARTICULO_ARTICULOID=p_articulo WHERE AGENDAID=p_id;
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe la cita.'); END IF; END;
  PROCEDURE PRC_CAMBIAR_ESTADO(p_id NUMBER,p_estado VARCHAR2) IS v_ag TALLER.AGENDA%ROWTYPE;
  BEGIN LOCK TABLE TALLER.AGENDA IN SHARE ROW EXCLUSIVE MODE; SELECT * INTO v_ag FROM TALLER.AGENDA WHERE AGENDAID=p_id;
    PRC_VALIDAR(p_id,v_ag.FECHA,v_ag.VEHICULO_PLACA,v_ag.EMPLEADO_CEDULA,p_estado,v_ag.ARTICULO_ARTICULOID);
    UPDATE TALLER.AGENDA SET ESTADO=p_estado WHERE AGENDAID=p_id; END;
  PROCEDURE PRC_ABRIR(p_resultado OUT SYS_REFCURSOR,p_id NUMBER DEFAULT NULL) IS BEGIN OPEN p_resultado FOR
    SELECT A.AGENDAID,A.FECHA,A.COMENTARIO,A.VEHICULO_PLACA,A.EMPLEADO_CEDULA,A.ESTADO,A.ARTICULO_ARTICULOID,CL.CEDULA CLIENTE_CEDULA,
      VP.PRIMER_NOMBRE CLIENTE_PRIMER_NOMBRE,VP.SEGUNDO_NOMBRE CLIENTE_SEGUNDO_NOMBRE,VP.PRIMER_APELLIDO CLIENTE_PRIMER_APELLIDO,VP.SEGUNDO_APELLIDO CLIENTE_SEGUNDO_APELLIDO,
      EP.PRIMER_NOMBRE EMPLEADO_PRIMER_NOMBRE,EP.SEGUNDO_NOMBRE EMPLEADO_SEGUNDO_NOMBRE,EP.PRIMER_APELLIDO EMPLEADO_PRIMER_APELLIDO,EP.SEGUNDO_APELLIDO EMPLEADO_SEGUNDO_APELLIDO,
      C.CARGOID,C.NOMBRECARGO,AR.NOMBRE NOMBRE_ARTICULO,AR.DURACION DURACION_SERVICIO
    FROM TALLER.AGENDA A JOIN TALLER.VEHICULO V ON V.PLACA=A.VEHICULO_PLACA JOIN TALLER.CLIENTE CL ON CL.CEDULA=V.CLIENTE_CEDULA JOIN TALLER.PERSONA VP ON VP.CEDULA=CL.CEDULA
    JOIN TALLER.EMPLEADO E ON E.CEDULA=A.EMPLEADO_CEDULA JOIN TALLER.PERSONA EP ON EP.CEDULA=E.CEDULA JOIN TALLER.CARGO C ON C.CARGOID=E.CARGO_CARGOID
    LEFT JOIN TALLER.ARTICULO AR ON AR.ARTICULOID=A.ARTICULO_ARTICULOID WHERE p_id IS NULL OR A.AGENDAID=p_id ORDER BY A.FECHA; END;
  PROCEDURE PRC_CONSULTAR(p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado); END;
  PROCEDURE PRC_BUSCAR_ID(p_id NUMBER,p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado,p_id); END;
  PROCEDURE PRC_ELIMINAR(p_id NUMBER) IS BEGIN DELETE FROM TALLER.AGENDA WHERE AGENDAID=p_id; IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe la cita.'); END IF; END;
  PROCEDURE PRC_CONTAR_PENDIENTES(p_total OUT NUMBER) IS BEGIN SELECT COUNT(*) INTO p_total FROM TALLER.AGENDA WHERE UPPER(ESTADO)='PENDIENTE'; END;
  PROCEDURE PRC_VALIDAR_DISPONIBILIDAD(p_empleado CHAR,p_fecha DATE,p_disponible OUT NUMBER) IS
  BEGIN p_disponible:=TALLER.FN_VALIDAR_DISPONIBILIDAD_EMPLEADO(p_empleado,p_fecha); END;
END PKG_AGENDA;
