CREATE OR REPLACE PACKAGE BODY TALLER.PKG_VEHICULO AS
  PROCEDURE PRC_ABRIR(p_resultado OUT SYS_REFCURSOR, p_placa CHAR DEFAULT NULL) IS
  BEGIN
    OPEN p_resultado FOR
      SELECT V.PLACA,V.MODELO,V.MARCA,V.TIPO_VEHICULO,V.COLOR,V.LINEA,V.CLIENTE_CEDULA,
        P.PRIMER_NOMBRE,P.SEGUNDO_NOMBRE,P.PRIMER_APELLIDO,P.SEGUNDO_APELLIDO,P.SEXO,P.TELEFONO,P.DIRECCION,P.CORREOELECTRONICO
      FROM TALLER.VEHICULO V JOIN TALLER.CLIENTE C ON C.CEDULA=V.CLIENTE_CEDULA
      JOIN TALLER.PERSONA P ON P.CEDULA=C.CEDULA
      WHERE p_placa IS NULL OR V.PLACA=p_placa
      ORDER BY V.PLACA;
  END;
  PROCEDURE PRC_GUARDAR(p_placa CHAR,p_modelo NUMBER,p_marca VARCHAR2,p_cliente CHAR,p_tipo VARCHAR2,p_color VARCHAR2,p_linea VARCHAR2) IS
  BEGIN INSERT INTO TALLER.VEHICULO(PLACA,MODELO,MARCA,CLIENTE_CEDULA,TIPO_VEHICULO,COLOR,LINEA)
    VALUES(p_placa,p_modelo,p_marca,p_cliente,p_tipo,p_color,p_linea); END;
  PROCEDURE PRC_MODIFICAR(p_placa CHAR,p_modelo NUMBER,p_marca VARCHAR2,p_cliente CHAR,p_tipo VARCHAR2,p_color VARCHAR2,p_linea VARCHAR2) IS
  BEGIN UPDATE TALLER.VEHICULO SET MODELO=p_modelo,MARCA=p_marca,CLIENTE_CEDULA=p_cliente,TIPO_VEHICULO=p_tipo,COLOR=p_color,LINEA=p_linea WHERE PLACA=p_placa;
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe el vehículo.'); END IF; END;
  PROCEDURE PRC_CONSULTAR(p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado); END;
  PROCEDURE PRC_BUSCAR_PLACA(p_placa CHAR,p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado,p_placa); END;
  PROCEDURE PRC_ELIMINAR(p_placa CHAR) IS BEGIN DELETE FROM TALLER.VEHICULO WHERE PLACA=p_placa;
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe el vehículo.'); END IF; END;
  PROCEDURE PRC_CONTAR(p_total OUT NUMBER) IS BEGIN SELECT COUNT(*) INTO p_total FROM TALLER.VEHICULO; END;
END PKG_VEHICULO;
