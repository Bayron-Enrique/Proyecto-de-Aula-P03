CREATE OR REPLACE PACKAGE BODY TALLER.PKG_CLIENTE AS
  PROCEDURE PRC_PERSONA(p_cedula CHAR,p_pnombre VARCHAR2,p_snombre VARCHAR2,p_papellido VARCHAR2,p_sapellido VARCHAR2,p_sexo CHAR,p_telefono VARCHAR2,p_direccion VARCHAR2,p_correo VARCHAR2) IS
  BEGIN MERGE INTO TALLER.PERSONA P USING(SELECT p_cedula CEDULA FROM DUAL) N ON(P.CEDULA=N.CEDULA)
    WHEN MATCHED THEN UPDATE SET P.PRIMER_NOMBRE=p_pnombre,P.SEGUNDO_NOMBRE=p_snombre,P.PRIMER_APELLIDO=p_papellido,P.SEGUNDO_APELLIDO=p_sapellido,P.SEXO=p_sexo,P.TELEFONO=p_telefono,P.DIRECCION=p_direccion,P.CORREOELECTRONICO=p_correo
    WHEN NOT MATCHED THEN INSERT(CEDULA,PRIMER_NOMBRE,SEGUNDO_NOMBRE,PRIMER_APELLIDO,SEGUNDO_APELLIDO,SEXO,TELEFONO,DIRECCION,CORREOELECTRONICO) VALUES(p_cedula,p_pnombre,p_snombre,p_papellido,p_sapellido,p_sexo,p_telefono,p_direccion,p_correo); END;
  PROCEDURE PRC_ABRIR(p_resultado OUT SYS_REFCURSOR,p_cedula CHAR DEFAULT NULL) IS BEGIN OPEN p_resultado FOR
    SELECT P.CEDULA,P.PRIMER_NOMBRE,P.SEGUNDO_NOMBRE,P.PRIMER_APELLIDO,P.SEGUNDO_APELLIDO,P.SEXO,P.TELEFONO,P.DIRECCION,P.CORREOELECTRONICO
    FROM TALLER.CLIENTE C JOIN TALLER.PERSONA P ON P.CEDULA=C.CEDULA WHERE p_cedula IS NULL OR C.CEDULA=p_cedula ORDER BY P.PRIMER_APELLIDO,P.PRIMER_NOMBRE; END;
  PROCEDURE PRC_GUARDAR(p_cedula CHAR,p_pnombre VARCHAR2,p_snombre VARCHAR2,p_papellido VARCHAR2,p_sapellido VARCHAR2,p_sexo CHAR,p_telefono VARCHAR2,p_direccion VARCHAR2,p_correo VARCHAR2) IS
  BEGIN SAVEPOINT SP_CLIENTE; LOCK TABLE TALLER.PERSONA IN SHARE ROW EXCLUSIVE MODE; PRC_PERSONA(p_cedula,p_pnombre,p_snombre,p_papellido,p_sapellido,p_sexo,p_telefono,p_direccion,p_correo); INSERT INTO TALLER.CLIENTE(CEDULA) VALUES(p_cedula);
  EXCEPTION WHEN OTHERS THEN ROLLBACK TO SP_CLIENTE; RAISE; END;
  PROCEDURE PRC_MODIFICAR(p_cedula CHAR,p_pnombre VARCHAR2,p_snombre VARCHAR2,p_papellido VARCHAR2,p_sapellido VARCHAR2,p_sexo CHAR,p_telefono VARCHAR2,p_direccion VARCHAR2,p_correo VARCHAR2) IS v_total NUMBER;
  BEGIN SELECT COUNT(*) INTO v_total FROM TALLER.CLIENTE WHERE CEDULA=p_cedula;
    IF v_total=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe el cliente.'); END IF;
    UPDATE TALLER.PERSONA SET PRIMER_NOMBRE=p_pnombre,SEGUNDO_NOMBRE=p_snombre,PRIMER_APELLIDO=p_papellido,SEGUNDO_APELLIDO=p_sapellido,SEXO=p_sexo,TELEFONO=p_telefono,DIRECCION=p_direccion,CORREOELECTRONICO=p_correo WHERE CEDULA=p_cedula; END;
  PROCEDURE PRC_CONSULTAR(p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado); END;
  PROCEDURE PRC_BUSCAR_CEDULA(p_cedula CHAR,p_resultado OUT SYS_REFCURSOR) IS BEGIN PRC_ABRIR(p_resultado,p_cedula); END;
  PROCEDURE PRC_ELIMINAR(p_cedula CHAR) IS
  BEGIN SAVEPOINT SP_CLIENTE; LOCK TABLE TALLER.PERSONA IN SHARE ROW EXCLUSIVE MODE; DELETE FROM TALLER.CLIENTE WHERE CEDULA=p_cedula;
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'No existe el cliente.'); END IF;
    DELETE FROM TALLER.PERSONA P WHERE P.CEDULA=p_cedula AND NOT EXISTS(SELECT 1 FROM TALLER.CLIENTE C WHERE C.CEDULA=P.CEDULA) AND NOT EXISTS(SELECT 1 FROM TALLER.EMPLEADO E WHERE E.CEDULA=P.CEDULA);
  EXCEPTION WHEN OTHERS THEN ROLLBACK TO SP_CLIENTE; RAISE; END;
  PROCEDURE PRC_CONTAR(p_total OUT NUMBER) IS BEGIN SELECT COUNT(*) INTO p_total FROM TALLER.CLIENTE; END;
  PROCEDURE PRC_VINCULAR_TELEGRAM(p_cedula CHAR,p_chat_id NUMBER) IS
    v_existe NUMBER;
    v_en_uso NUMBER;
  BEGIN
    IF p_chat_id IS NULL THEN RAISE_APPLICATION_ERROR(-20040,'El identificador de Telegram es obligatorio.'); END IF;

    SELECT COUNT(*) INTO v_existe FROM TALLER.CLIENTE WHERE CEDULA=p_cedula;
    IF v_existe=0 THEN RAISE_APPLICATION_ERROR(-20041,'No existe el cliente que se desea vincular.'); END IF;

    SELECT COUNT(*) INTO v_en_uso FROM TALLER.CLIENTE
     WHERE TELEGRAM_CHAT_ID=p_chat_id AND CEDULA<>p_cedula;
    IF v_en_uso>0 THEN RAISE_APPLICATION_ERROR(-20042,'Esta cuenta de Telegram ya está vinculada a otro cliente.'); END IF;

    UPDATE TALLER.CLIENTE SET TELEGRAM_CHAT_ID=p_chat_id WHERE CEDULA=p_cedula;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
    RAISE_APPLICATION_ERROR(-20042,'Esta cuenta de Telegram ya está vinculada a otro cliente.');
  END;
  PROCEDURE PRC_BUSCAR_POR_TELEGRAM_CHAT_ID(p_chat_id NUMBER,p_resultado OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_resultado FOR
      SELECT P.CEDULA,P.PRIMER_NOMBRE,P.SEGUNDO_NOMBRE,P.PRIMER_APELLIDO,P.SEGUNDO_APELLIDO,
             P.SEXO,P.TELEFONO,P.DIRECCION,P.CORREOELECTRONICO,C.TELEGRAM_CHAT_ID
        FROM TALLER.CLIENTE C JOIN TALLER.PERSONA P ON P.CEDULA=C.CEDULA
       WHERE C.TELEGRAM_CHAT_ID=p_chat_id;
  END;
END PKG_CLIENTE;
