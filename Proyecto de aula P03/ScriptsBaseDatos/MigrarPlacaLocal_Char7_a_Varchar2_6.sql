-- Elimina dinámicamente las cuatro FK actuales que apuntan a VEHICULO_PK.
-- Incluye la FK sin nombre explícito de DETALLE_VEHICULO.
DECLARE
  v_pk_vehiculo USER_CONSTRAINTS.CONSTRAINT_NAME%TYPE;
BEGIN
  SELECT CONSTRAINT_NAME
    INTO v_pk_vehiculo
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'VEHICULO'
     AND CONSTRAINT_TYPE = 'P';

  FOR fk IN (
    SELECT C.TABLE_NAME, C.CONSTRAINT_NAME
      FROM USER_CONSTRAINTS C
      JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
     WHERE C.CONSTRAINT_TYPE = 'R'
       AND C.R_CONSTRAINT_NAME = v_pk_vehiculo
       AND C.TABLE_NAME IN ('AGENDA', 'DETALLE_VEHICULO',
                            'NOTIFICACION_MANTENIMIENTO', 'SOAT')
       AND CC.COLUMN_NAME = 'VEHICULO_PLACA'
  ) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE TALLER.' || fk.TABLE_NAME ||
                      ' DROP CONSTRAINT ' || fk.CONSTRAINT_NAME;
  END LOOP;
END;
/

